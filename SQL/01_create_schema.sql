CREATE OR REPLACE VIEW v_products_current AS
SELECT
    p.id,
    p.name,
    p.description,
    p.is_active,
    c.id AS category_id,
    c.name AS category_name,
    pp.price,
    pp.currency_code,
    ps.quantity AS stock_quantity
FROM products p
LEFT JOIN product_categories c ON c.id = p.category_id
LEFT JOIN product_prices pp ON pp.product_id = p.id
LEFT JOIN product_stocks ps ON ps.product_id = p.id;

CREATE OR REPLACE VIEW v_order_items_details AS
SELECT
    oi.id,
    oi.order_id,
    oi.product_id,
    p.name AS product_name,
    oi.quantity,
    pp.price AS unit_price,
    pp.currency_code,
    oi.quantity * pp.price AS line_total
FROM order_items oi
JOIN products p ON p.id = oi.product_id
LEFT JOIN product_prices pp ON pp.product_id = p.id;

CREATE OR REPLACE VIEW v_order_totals AS
SELECT
    o.id AS order_id,
    o.order_number,
    COALESCE(SUM(oid.line_total), 0) AS total_amount,
    MAX(oid.currency_code) AS currency_code
FROM orders o
LEFT JOIN v_order_items_details oid ON oid.order_id = o.id
GROUP BY o.id, o.order_number;

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_app_users_updated_at ON app_users;
CREATE TRIGGER trg_app_users_updated_at
BEFORE UPDATE ON app_users
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

